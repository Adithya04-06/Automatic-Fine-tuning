"""Architectural profiling script using ModelAnalyzer for ResNet-18, EfficientNet-B0, and ViT-B/16."""

import json
import os
import sys
from typing import Any, Dict, List

# Add project root to sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import torch
from src.models.backbones import build_model
from src.models.model_analyzer import ModelAnalyzer, ModelArchitectureInfo, ScopeDefinition
from src.models.scope_manager import ScopeManager


def profile_architecture(arch_name: str, num_classes: int = 10) -> Dict[str, Any]:
    """Inspects a model architecture and profiles its structural components and progressive fine-tuning scopes."""
    model = build_model(backbone_name=arch_name, num_classes=num_classes, pretrained=False)
    family = ModelAnalyzer.detect_family(model)
    arch_info: ModelArchitectureInfo = ModelAnalyzer.inspect_model(model)
    scopes: List[ScopeDefinition] = ModelAnalyzer.generate_scopes(model)

    stages_profile = []
    for s in arch_info.stages:
        stages_profile.append({
            "stage_idx": s.stage_idx,
            "stage_name": s.name,
            "param_count": s.param_count,
            "tensor_count": len(s.param_names),
            "sample_tensors": s.param_names[:4],
        })

    scopes_profile = []
    for scope in scopes:
        ScopeManager.apply_scope(model, scope)
        trainable_p, total_p, ratio = ScopeManager.count_parameters(model)
        frozen_p = total_p - trainable_p

        scopes_profile.append({
            "strategy_id": scope.strategy_id,
            "name": scope.name,
            "description": scope.description,
            "unfrozen_targets": list(scope.unfrozen_submodules),
            "trainable_parameters": trainable_p,
            "frozen_parameters": frozen_p,
            "total_parameters": total_p,
            "trainable_percentage": round(ratio * 100, 4),
        })

    return {
        "architecture_name": arch_name,
        "family": family,
        "total_parameters": arch_info.total_params,
        "classification_head": {
            "name": arch_info.head.name,
            "param_count": arch_info.head.param_count,
            "tensor_count": len(arch_info.head.param_names),
            "tensors": arch_info.head.param_names,
        },
        "stem": {
            "name": arch_info.stem.name,
            "param_count": arch_info.stem.param_count,
            "tensor_count": len(arch_info.stem.param_names),
            "sample_tensors": arch_info.stem.param_names[:4],
        },
        "stages": stages_profile,
        "fine_tuning_scopes": scopes_profile,
    }


def generate_markdown_report(profiles: List[Dict[str, Any]], output_path: str):
    """Generates a human-readable Markdown profiling report."""
    lines = [
        "# Model Analyzer Structural & Scope Profiling Report",
        "",
        "This report documents the structural discovery, stage identification, classification head isolation, "
        "and progressive fine-tuning scopes generated by the **Model Analyzer** across **ResNet-18**, **EfficientNet-B0**, and **Vision Transformer (ViT-B/16)**.",
        "",
        "---",
        "",
    ]

    for p in profiles:
        lines.append(f"## 🏛️ Architecture: {p['architecture_name'].upper()} (Family: `{p['family'].upper()}`)")
        lines.append(f"- **Total Model Parameters**: {p['total_parameters']:,}")
        lines.append(f"- **Classification Head**: `{p['classification_head']['name']}` ({p['classification_head']['param_count']:,} parameters)")
        lines.append(f"- **Feature Extraction Stem**: `{p['stem']['name']}` ({p['stem']['param_count']:,} parameters)")
        lines.append(f"- **Identified Feature Stages**: {len(p['stages'])} progressive stages")
        lines.append("")
        lines.append("### Stage Decomposition")
        lines.append("| Stage Index | Stage Identifier | Parameter Count | Tensor Count | Sample Tensors |")
        lines.append("| :---: | :--- | :---: | :---: | :--- |")
        for s in p["stages"]:
            sample_str = "`" + "`, `".join(s["sample_tensors"][:2]) + "`"
            lines.append(f"| {s['stage_idx']} | `{s['stage_name']}` | {s['param_count']:,} | {s['tensor_count']} | {sample_str} |")
        lines.append("")
        lines.append("### Candidate Progressive Fine-Tuning Scopes")
        lines.append("| ID | Strategy Name | Trainable Params | Frozen Params | % Trainable | Unfrozen Submodule Targets |")
        lines.append("| :---: | :--- | :---: | :---: | :---: | :--- |")
        for s in p["fine_tuning_scopes"]:
            targets = "`" + "`, `".join(s["unfrozen_targets"][:3]) + ("`..." if len(s["unfrozen_targets"]) > 3 else "`")
            lines.append(f"| **{s['strategy_id']}** | `{s['name']}` | {s['trainable_parameters']:,} | {s['frozen_parameters']:,} | {s['trainable_percentage']:.2f}% | {targets} |")
        lines.append("")
        lines.append("---")
        lines.append("")

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    output_dir = "./outputs/profiling"
    os.makedirs(output_dir, exist_ok=True)

    architectures = ["resnet18", "efficientnet_b0", "vit_b_16"]
    profiles = []

    print("\n" + "=" * 90)
    print("RUNNING MODEL ANALYZER ARCHITECTURAL PROFILING (NO TRAINING)")
    print("=" * 90)

    for arch in architectures:
        print(f"Profiling {arch.upper()}...")
        prof = profile_architecture(arch, num_classes=10)
        profiles.append(prof)

    # Save JSON Report
    json_path = os.path.join(output_dir, "model_analyzer_profile.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(profiles, f, indent=2)
    print(f"\nSaved structured profiling data to: {json_path}")

    # Save Markdown Report
    md_path = os.path.join(output_dir, "model_analyzer_profile.md")
    generate_markdown_report(profiles, md_path)
    print(f"Saved Markdown report to: {md_path}")

    print("\n" + "=" * 90)
    print("MODEL ANALYZER PROFILING COMPLETE.")
    print("=" * 90 + "\n")


if __name__ == "__main__":
    main()
